"""Write web/public/skills/: one static page per SAT skill, an index, and the sitemap.

The app is one JavaScript page at one URL, so a search engine has a single
page to rank. These give each of the 29 skills its own crawlable page: the
skill's name, how many official questions it has, and our question types for
it (from process-types.json) with links that open practice straight away
(the ?skill= and ?type= deep links in web/src/App.tsx).

    python3 scripts/skill_pages.py

Reads names and difficulty counts from the local bank (data/bluebank.db, never
committed) and writes only our own text plus College Board's skill names and
counts: no question content. Re-run after process-types.json changes.
"""
import html
import json
import re
import sqlite3
from collections import Counter
from pathlib import Path
from urllib.parse import quote

DB = Path("data/bluebank.db")
TYPES = Path("web/public/process-types.json")
OUT = Path("web/public/skills")
SITEMAP = Path("web/public/sitemap.xml")
SITE = "https://lightblueprep.pages.dev"

SECTION = {"RW": "Reading and Writing", "MATH": "Math"}

CSS = """
:root { color-scheme: light; }
* { margin: 0; padding: 0; box-sizing: border-box; }
body { background: #fff; color: #17181a; line-height: 1.6; padding: 28px 20px 96px;
  font-family: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }
main { max-width: 720px; margin: 0 auto; }
a { color: #1479c2; }
.brand { display: inline-flex; align-items: center; gap: 10px; margin-bottom: 40px;
  font-weight: 800; font-size: 19px; letter-spacing: -.03em; color: #17181a; text-decoration: none; }
.brand img { width: 32px; height: 32px; }
.brand b { color: #1479c2; }
.RW { --sec: #a3245a; --sec-bg: #fdf2f7; }
.MATH { --sec: #075f99; --sec-bg: #eff8ff; }
.eyebrow { font-size: 13px; font-weight: 700; letter-spacing: .06em; text-transform: uppercase; color: var(--sec); }
h1 { font-size: clamp(30px, 6vw, 44px); line-height: 1.1; letter-spacing: -.03em; margin: 6px 0 14px; }
.lede { font-size: 18px; color: #3b3e43; margin-bottom: 22px; }
.cta { display: inline-block; background: #1479c2; color: #fff; font-weight: 700; text-decoration: none;
  padding: 12px 22px; border-radius: 999px; }
.cta:hover { background: #0f5f9a; }
h2 { font-size: 21px; letter-spacing: -.015em; margin: 44px 0 8px; }
h2 + p { color: #4a4d52; margin-bottom: 14px; }
.rows { list-style: none; border-top: 1px solid #e3e5e8; }
.rows li { border-bottom: 1px solid #e3e5e8; }
.rows a { display: block; padding: 13px 4px; color: inherit; text-decoration: none; }
.rows a:hover .t { color: #1479c2; }
.t { display: flex; justify-content: space-between; gap: 14px; font-weight: 650; }
.n { color: #63666b; font-weight: 500; white-space: nowrap; }
.how { display: block; color: #4a4d52; font-size: 15px; }
.chips { list-style: none; display: flex; flex-wrap: wrap; gap: 8px; }
.chips a { display: inline-block; padding: 6px 14px; border: 1px solid #d5d8dc; border-radius: 999px;
  color: #17181a; font-size: 15px; text-decoration: none; }
.chips a:hover { border-color: #1479c2; color: #1479c2; }
.domain { margin: 34px 0 6px; font-size: 18px; color: var(--sec); }
footer { margin-top: 56px; padding-top: 18px; border-top: 1px solid #e3e5e8; font-size: 14px; color: #63666b; }
"""


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def page(title, description, path, body, section=""):
    url = SITE + path
    e = html.escape
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>{e(title)}</title>
    <meta name="description" content="{e(description)}" />
    <link rel="canonical" href="{url}" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <link rel="icon" type="image/png" sizes="48x48" href="/favicon-48.png" />
    <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
    <meta name="theme-color" content="#1479c2" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="LightBluePrep" />
    <meta property="og:url" content="{url}" />
    <meta property="og:title" content="{e(title)}" />
    <meta property="og:description" content="{e(description)}" />
    <meta property="og:image" content="{SITE}/og-card.png" />
    <meta name="twitter:card" content="summary_large_image" />
    <!-- Generated by scripts/skill_pages.py. Edit the script, not this file. -->
    <style>{CSS}</style>
  </head>
  <body>
    <main class="{section}">
      <a class="brand" href="/"><img src="/favicon.svg" alt="" /><span>Light<b>Blue</b>Prep</span></a>
{body}
      <footer>
        Free, no account, no ads. LightBluePrep is a free student project, not
        affiliated with or endorsed by College Board. SAT and Bluebook are
        trademarks of College Board. <a href="/privacy">Privacy</a>
      </footer>
    </main>
  </body>
</html>
"""


def main():
    conn = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    rows = conn.execute(
        "SELECT section, domain, domain_name, skill, skill_name, difficulty FROM questions"
    ).fetchall()
    pt = json.loads(TYPES.read_text())
    per_type = Counter(pt["q"].values())

    skills = {}
    for section, domain, domain_name, skill, skill_name, difficulty in rows:
        s = skills.setdefault(skill, {
            "code": skill, "section": section, "domain": domain,
            # Keyed by code: CB spells one skill two ways ("Cross-text" / "Cross-Text").
            "domain_name": domain_name.strip(), "name": skill_name.strip(), "diff": Counter(),
        })
        s["diff"][difficulty] += 1
    order = sorted(skills.values(), key=lambda s: (s["section"] != "RW", s["domain"], s["code"]))
    for s in order:
        s["slug"] = slug(s["name"])
        s["n"] = sum(s["diff"].values())

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.html"):
        old.unlink()
    e = html.escape
    for s in order:
        types = pt["types"].get(s["code"], {})
        ranked = sorted(types.items(), key=lambda kv: -per_type[f"{s['code']}.{kv[0]}"])
        type_rows = "\n".join(
            f'          <li><a href="/?type={quote(s["code"] + "." + key)}">'
            f'<span class="t">{e(t["label"])}<span class="n">{per_type[s["code"] + "." + key]} questions</span></span>'
            f'<span class="how">{e(t["how"])}</span></a></li>'
            for key, t in ranked)
        siblings = "\n".join(
            f'          <li><a href="/skills/{o["slug"]}">{e(o["name"])}</a></li>'
            for o in order if o["domain"] == s["domain"] and o is not s)
        d = s["diff"]
        body = f"""      <p class="eyebrow">SAT {SECTION[s["section"]]} · {e(s["domain_name"])}</p>
      <h1>{e(s["name"])}</h1>
      <p class="lede">{s["n"]} official College Board practice questions on this skill, free:
        {d["E"]} easy, {d["M"]} medium and {d["H"]} hard. No account needed.</p>
      <a class="cta" href="/?skill={quote(s["code"])}">Practice all {s["n"]} questions</a>
      <h2>{len(types)} question types</h2>
      <p>Every question here is sorted by how you solve it. Pick one type and practice it until it sticks.</p>
      <ul class="rows">
{type_rows}
      </ul>
      <h2>More {e(s["domain_name"])}</h2>
      <ul class="chips">
{siblings}
      </ul>
      <p style="margin-top:22px"><a href="/skills/">Every SAT skill</a></p>"""
        (OUT / f"{s['slug']}.html").write_text(page(
            f"{s['name']}: free SAT practice questions · LightBluePrep",
            f"{s['n']} official College Board SAT practice questions on {s['name']}, free, "
            f"sorted into {len(types)} question types by how you solve them. No account needed.",
            f"/skills/{s['slug']}", body, s["section"]))

    groups = []
    for section in ("RW", "MATH"):
        inner = []
        for domain in dict.fromkeys(s["domain"] for s in order if s["section"] == section):
            members = [s for s in order if s["domain"] == domain]
            links = "\n".join(
                f'          <li><a href="/skills/{s["slug"]}"><span class="t">{e(s["name"])}'
                f'<span class="n">{s["n"]} questions</span></span></a></li>' for s in members)
            inner.append(f'      <h3 class="domain">{e(members[0]["domain_name"])}</h3>\n'
                         f'      <ul class="rows">\n{links}\n      </ul>')
        groups.append(f'      <section class="{section}">\n      <h2>{SECTION[section]}</h2>\n'
                      + "\n".join(inner) + "\n      </section>")
    total = sum(s["n"] for s in order)
    body = f"""      <p class="eyebrow" style="color:#1479c2">Free SAT practice by skill</p>
      <h1>Every SAT skill</h1>
      <p class="lede">All {total:,} official College Board practice questions, sorted into the
        {len(order)} skills the Digital SAT tests and then by how you solve them. Free, no account.</p>
      <a class="cta" href="/">Start practicing</a>
{chr(10).join(groups)}"""
    (OUT / "index.html").write_text(page(
        "Every SAT skill, with free practice questions · LightBluePrep",
        f"All {total:,} official College Board SAT practice questions, free, sorted by skill "
        "and by how you solve them. Reading and Writing and Math.",
        "/skills/", body))

    urls = ["/", "/skills/"] + [f"/skills/{s['slug']}" for s in order] + ["/privacy"]
    SITEMAP.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{SITE}{u}</loc></url>\n" for u in urls)
        + "</urlset>\n")
    print(f"wrote {len(order)} skill pages, skills/index.html and {len(urls)} sitemap urls")


if __name__ == "__main__":
    main()
